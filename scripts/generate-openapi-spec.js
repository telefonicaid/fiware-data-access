// Dumps the OpenAPI spec generated by swagger-jsdoc (from the @swagger JSDoc blocks in
// src/routes/*.js and src/lib/openapiComponents.js) to a JSON file, so it can be validated
// by external tools (swagger-cli, @redocly/cli) without those tools having to understand
// swagger-jsdoc themselves.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { openApiSpec } from '../src/lib/openapi.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = join(__dirname, '../openapi.generated.json');

writeFileSync(outputPath, JSON.stringify(openApiSpec, null, 2));

console.log(`OpenAPI spec written to ${outputPath}`);
console.log(`Paths: ${Object.keys(openApiSpec.paths ?? {}).length}`);
